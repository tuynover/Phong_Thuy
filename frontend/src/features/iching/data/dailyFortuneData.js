// Helper lấy chuỗi ngày YYYY-MM-DD theo giờ địa phương
export function getTodayDateString() {
  const today = new Date();
  return `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, '0')}-${String(today.getDate()).padStart(2, '0')}`;
}

export const DAILY_FORTUNE_EVENT = 'phongthuy_daily_fortune_changed';

// Helper lấy key lưu trữ localStorage
export function getDailyFortuneStorageKey(userId) {
  const todayStr = getTodayDateString();
  return `daily_fortune_${todayStr}_${userId || 'guest'}`;
}

// Kiểm tra hôm nay người dùng đã gieo quẻ chưa
export function checkHasDrawnDailyFortune(userId) {
  if (typeof window === 'undefined') return false;
  try {
    const key = getDailyFortuneStorageKey(userId);
    const saved = localStorage.getItem(key);
    return !!saved;
  } catch (e) {
    return false;
  }
}

// Lưu kết quả gieo quẻ và phát thông báo sự kiện cập nhật
export function saveDailyFortuneResult(fortune, userId) {
  if (typeof window === 'undefined') return;
  try {
    const key = getDailyFortuneStorageKey(userId);
    localStorage.setItem(key, JSON.stringify(fortune));
    window.dispatchEvent(new CustomEvent(DAILY_FORTUNE_EVENT, { detail: { userId, hasDrawn: true } }));
  } catch (e) {}
}

// Helper lấy ngẫu nhiên 1 quẻ trong 64 quẻ (Random Selection)
export function getRandomDailyFortune() {
  if (typeof crypto !== 'undefined' && crypto.getRandomValues) {
    const array = new Uint32Array(1);
    crypto.getRandomValues(array);
    const index = array[0] % DAILY_FORTUNES.length;
    return DAILY_FORTUNES[index];
  }
  const randomIndex = Math.floor(Math.random() * DAILY_FORTUNES.length);
  return DAILY_FORTUNES[randomIndex];
}

// Giữ getDailyFortune để tương thích ngược, trả về quẻ ngẫu nhiên (random)
export function getDailyFortune() {
  return getRandomDailyFortune();
}

